export function buildGlobalCatalogRecords(): {
  tests: LabTest[];
  testParameters: TestParameter[];
} {
  const tests: LabTest[] = [];
  const testParameters: TestParameter[] = [];

  for (const def of GLOBAL_MEDICAL_TESTS_DEFINITIONS) {
    tests.push({
      id: def.id,
      code: def.code,
      nameAr: def.nameAr,
      nameEn: def.nameEn,
      department: def.department,
      sampleType: def.sampleType,
      tubeType: def.tubeType,
      turnaroundTime: def.turnaroundTime,
      price: def.price,
      estimatedCost: def.estimatedCost,
      active: true,
      commissionEligible: def.commissionEligible,
      notes:
        def.notes ||
        'تقرير مرجعي معتمد وفق المعايير الإكلينيكية العالمية (WHO / CLSI / IFCC / CAP)',
    });

    def.parameters.forEach((prm, idx) => {
      testParameters.push({
        id: `${def.id}_prm_${idx + 1}`,
        testId: def.id,
        code: prm.code,
        nameAr: prm.nameAr,
        nameEn: prm.nameEn,
        unit: prm.unit,
        normalMaleMin: prm.minM,
        normalMaleMax: prm.maxM,
        normalFemaleMin: prm.minF ?? prm.minM,
        normalFemaleMax: prm.maxF ?? prm.maxM,
        normalRangeText:
          prm.rangeText || `${prm.minM} - ${prm.maxM} ${prm.unit}`.trim(),
        criticalLow: prm.critLow ?? 0,
        criticalHigh: prm.critHigh ?? 999,
        resultType: prm.type || 'numeric',
        options: prm.options,
        decimalPlaces: prm.decimals ?? 1,
        sortOrder: idx + 1,
        active: true,
      });
    });
  }

  return { tests, testParameters };
}

let catalogSyncPromise: Promise<{ testsAdded: number; parametersSynced: number }> | null = null;

/**
 * Ensures the global medical tests encyclopedia and all its detailed parameters
 * are synchronized into IndexedDB (`db.tests` and `db.testParameters`).
 */
export async function syncGlobalMedicalCatalog(forceOverwrite = false): Promise<{
  testsAdded: number;
  parametersSynced: number;
}> {
  if (!forceOverwrite && catalogSyncPromise) {
    return catalogSyncPromise;
  }

  const runSync = async () => {
    const { tests: globalTests, testParameters: globalParams } = buildGlobalCatalogRecords();
    const existingTests = await db.tests.toArray();
    const existingParams = await db.testParameters.toArray();

    // If we already have >= 85 tests and >= 300 parameters and not forceOverwrite, skip heavy write
    if (!forceOverwrite && existingTests.length >= 85 && existingParams.length >= 300) {
      return { testsAdded: 0, parametersSynced: 0 };
    }

    const existingByCode = new Map(existingTests.map((t) => [t.code.toUpperCase(), t]));
    const existingById = new Map(existingTests.map((t) => [t.id, t]));

    const testsToPut: LabTest[] = [];
    const paramsToPut: TestParameter[] = [];
    const testIdsWithUpgradedParams = new Set<string>();

    for (const gt of globalTests) {
      const matched = existingById.get(gt.id) || existingByCode.get(gt.code.toUpperCase());
      const targetTestId = matched ? matched.id : gt.id;

      testsToPut.push({
        ...gt,
        id: targetTestId,
        price: matched && !forceOverwrite ? matched.price : gt.price,
      });

      const currentParamsForTest = existingParams.filter((p) => p.testId === targetTestId);
      const hasLegacySinglePlaceholder =
        currentParamsForTest.length === 1 && currentParamsForTest[0].code.endsWith('-VAL');

      const defParams = globalParams.filter((p) => p.testId === gt.id);

      if (
        forceOverwrite ||
        currentParamsForTest.length === 0 ||
        hasLegacySinglePlaceholder ||
        currentParamsForTest.length < defParams.length
      ) {
        testIdsWithUpgradedParams.add(targetTestId);
        defParams.forEach((dp, idx) => {
          // Preserve prm_1..prm_9 IDs for tst_1 and tst_4 if they match index so existing demo results stay linked
          let paramId = `${targetTestId}_prm_${idx + 1}`;
          if (targetTestId === 'tst_1' && idx < 5 && currentParamsForTest[idx]) {
            paramId = currentParamsForTest[idx].id;
          } else if (targetTestId === 'tst_4' && idx < 4 && currentParamsForTest[idx]) {
            paramId = currentParamsForTest[idx].id;
          }
          paramsToPut.push({
            ...dp,
            id: paramId,
            testId: targetTestId,
          });
        });
      }
    }

    await db.transaction('rw', [db.tests, db.testParameters], async () => {
      if (testIdsWithUpgradedParams.size > 0) {
        for (const tid of testIdsWithUpgradedParams) {
          await db.testParameters.where('testId').equals(tid).delete();
        }
      }
      await db.tests.bulkPut(testsToPut);
      if (paramsToPut.length > 0) {
        await db.testParameters.bulkPut(paramsToPut);
      }
    });

    CacheService.invalidate('catalog:tests:all');
    CacheService.invalidate('catalog:params:all');
    CacheService.invalidatePrefix('catalog:params:test:');

    return {
      testsAdded: testsToPut.length,
      parametersSynced: paramsToPut.length,
    };
  };

  if (forceOverwrite) {
    return runSync();
  }
  catalogSyncPromise = runSync();
  return catalogSyncPromise;
}
