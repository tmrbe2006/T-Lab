const p = (
  code: string,
  nameAr: string,
  nameEn: string,
  unit: string,
  minM: number,
  maxM: number,
  rangeText?: string,
  critLow?: number,
  critHigh?: number,
  type: ParameterResultType = 'numeric',
  decimals = 1,
  minF?: number,
  maxF?: number,
  options?: string[]
): GlobalParamDef => ({
  code,
  nameAr,
  nameEn,
  unit,
  minM,
  maxM,
  minF: minF ?? minM,
  maxF: maxF ?? maxM,
  rangeText: rangeText || (type === 'numeric' ? `${minM} - ${maxM} ${unit}`.trim() : 'Negative / Normal'),
  critLow: critLow ?? (type === 'numeric' ? Number((minM * 0.45).toFixed(2)) : 0),
  critHigh: critHigh ?? (type === 'numeric' ? Number((maxM * 2.5).toFixed(2)) : 999),
  type,
  decimals,
  options,
});

